/* 句子里会变的那几段：{} 换成 (.+?)，整句锚定。没有 {} 的直接查表。 */
const DESK_EN_EXACT = new Map(), DESK_EN_PAT = [];
for (const [zh, en] of Object.entries(DESK_EN)) {
  if (!zh.includes("{}")) { DESK_EN_EXACT.set(zh, en); continue; }
  const re = new RegExp("^" + zh.split("{}").map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("([\\s\\S]*?)") + "$");
  DESK_EN_PAT.push([re, en]);
}
// 长句在前：短的模式（「{} 在跑」）别抢了长的
DESK_EN_PAT.sort((a, b) => b[0].source.length - a[0].source.length);
const HAS_CJK = /[㐀-鿿　-〿！-～]/;
function deskTr(s) {
  if (PERCH_LOCALE !== "en" || !s || !HAS_CJK.test(s)) return s;
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s);
  const core = m[2];
  let out = DESK_EN_EXACT.get(core);
  if (out === undefined) {
    for (const [re, en] of DESK_EN_PAT) {
      const hit = re.exec(core);
      if (!hit) continue;
      let i = 1;
      // 带过去的那几段里如果还是一句表里有的话（「在等你：提问」），也换掉
      out = en.replace(/\{\}/g, () => { const part = hit[i++] || ""; const t2 = DESK_EN_EXACT.get(part.trim()); return t2 !== undefined ? t2 : part; });
      break;
    }
  }
  // 对不上整句：按「 · 」切开，每段能换的换掉（「空闲 · termtest」→「Idle · termtest」）
  if (out === undefined && core.includes(" · ")) {
    const parts = core.split(" · ");
    const tr = parts.map((x) => { const e = DESK_EN_EXACT.get(x); return e === undefined ? x : e; });
    if (tr.some((x, i) => x !== parts[i])) out = tr.join(" · ");
  }
  return out === undefined ? s : m[1] + out + m[3];
}

